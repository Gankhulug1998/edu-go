_MARKS = {'a':'āáǎà','o':'ōóǒò','e':'ēéěè','i':'īíǐì','u':'ūúǔù','ü':'ǖǘǚǜ'}
def _num2dia(syl):
    m = re.search(r'[1-5]$', syl); tone = int(m.group()) if m else 0
    if m: syl = syl[:-1]
    syl = syl.replace('u:','ü').replace('U:','Ü').replace('v','ü')
    if tone in (0,5): return syl
    low = syl.lower()
    if 'a' in low: tgt='a'
    elif 'e' in low: tgt='e'
    elif 'ou' in low: tgt='o'
    else: tgt = next((c for c in reversed(low) if c in 'aeiouü'), None)
    if not tgt: return syl
    out=[]; done=False
    for ch in syl:
        if not done and ch.lower()==tgt:
            mk=_MARKS[tgt][tone-1]; out.append(mk if ch.islower() else mk.upper()); done=True
        else: out.append(ch)
    return ''.join(out)
