IDS_BIN=set('⿰⿱⿴⿵⿶⿷⿸⿹⿺⿻'); IDS_TRI=set('⿲⿳')
def parse(s,i=0):
    c=s[i]
    if c in IDS_BIN:
        a,i=parse(s,i+1); b,i=parse(s,i); return ('op',c,[a,b]),i
    if c in IDS_TRI:
        a,i=parse(s,i+1); b,i=parse(s,i); d,i=parse(s,i); return ('op',c,[a,b,d]),i
    return ('leaf',c),i+1
def leaves(n):
    if n[0]=='leaf': return [n[1]]
    out=[]
    for c in n[2]: out+=leaves(c)
    return out
def toplevel(dec):
    if '？' in dec or not dec: return None
    try: t,_=parse(dec)
    except: return None
    if t[0]=='leaf': return None
    if all(c[0]=='leaf' for c in t[2]): return [c[1] for c in t[2]]
    lv=leaves(t)
    if len(set(lv))==1: return lv
    if len(lv)<=3: return lv
    return None

def make_card(ch):
    d = CH[ch]; meaning, exw, exmn = d
    py = g[ch]['pinyin']
    parts = toplevel(mmah[ch]['decomposition'])
    # compound эсэхийг шийдэх: бүх бүрэлдэхүүн COMPONENT_MN-д, fragment байхгүй
    is_compound = (parts is not None and 2 <= len(parts) <= 3
                   and all(p in COMPONENT_MN for p in parts)
                   and not any(p in FRAG for p in parts))
    expy = EX_PY.get(exw) or ced.get(exw) or wpy.get(exw) or py
    card = {
        'character': ch, 'pinyin': py, 'meaning': meaning,
        'kind': 'compound' if is_compound else 'simple',
        'example': {'word': exw, 'pinyin': expy, 'translation': exmn},
        'level': 1, 'category': category(ch), 'tags': ['hsk1'],
    }
    if is_compound:
        labels = [COMPONENT_MN[p] for p in parts]
        card['structure'] = {'parts':[{'char':p,'label':l} for p,l in zip(parts,labels)],
                             'result':{'char':ch,'label':meaning}}
        if len(set(parts))==1:
            card['story'] = f"{labels[0]} ({parts[0]}) {len(parts)} удаа давтагдаж «{meaning}» гэсэн утгыг илэрхийлнэ."
        else:
            j = ', '.join(f"{l} ({p})" for p,l in zip(parts,labels))
            card['story'] = f"{j} хослон «{meaning}» гэсэн утга үүсгэнэ."
        card['mnemonic'] = {'parts':parts,'result':ch,'meaning':meaning}
    else:
        card['structure'] = {'parts':[], 'result':{'char':ch,'label':meaning}}
        card['story'] = f"«{meaning}» гэсэн утгатай үндсэн дүрс ханз ({py})."
    return card

