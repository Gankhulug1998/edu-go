def n2d(s):
    m=re.search(r'[1-5]$',s); t=int(m.group()) if m else 0
    if m: s=s[:-1]
    s=s.replace('u:','ü').replace('U:','Ü').replace('v','ü')
    if t in (0,5): return s
    lo=s.lower()
    tg='a' if 'a' in lo else 'e' if 'e' in lo else 'o' if 'ou' in lo else next((c for c in reversed(lo) if c in 'aeiouü'),None)
    if not tg: return s
    o=[];d=False
    for c in s:
        if not d and c.lower()==tg: mk=_M[tg][t-1]; o.append(mk if c.islower() else mk.upper()); d=True
        else: o.append(c)
    return ''.join(o)
