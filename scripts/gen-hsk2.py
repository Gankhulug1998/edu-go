by = {c['character']: c for c in cards}
added=0; existing=0; comp=0; simp=0; pyov=0; exfb=[]
for ch in CH:
    if ch in by:
        existing+=1; continue
    meaning, exw, exmn = CH[ch]
    py = PY_OVERRIDE.get(ch) or g[ch]['pinyin']
    if ch in PY_OVERRIDE: pyov+=1
    parts = toplevel(mmah[ch]['decomposition'])
    is_comp = (parts is not None and 2<=len(parts)<=3
               and all(p in COMPONENT_MN for p in parts) and not any(p in FRAG for p in parts))
    expy = EX_PY.get(exw) or ced.get(exw) or wpy.get(exw) or py
    if exw not in EX_PY and exw not in ced and exw not in wpy: exfb.append((ch,exw))
    card={'character':ch,'pinyin':py,'meaning':meaning,
          'kind':'compound' if is_comp else 'simple',
          'example':{'word':exw,'pinyin':expy,'translation':exmn},
          'level':2,'category':category(ch),'tags':['hsk2'],
          'images':{'icon':{'kind':'emoji','emoji':EMО.get(ch,'🔣')}}}
    if is_comp:
        lbl=[COMPONENT_MN[p] for p in parts]
        card['structure']={'parts':[{'char':p,'label':l} for p,l in zip(parts,lbl)],
                           'result':{'char':ch,'label':meaning}}
        if len(set(parts))==1:
            card['story']=f"{lbl[0]} ({parts[0]}) {len(parts)} удаа давтагдаж «{meaning}» гэсэн утгыг илэрхийлнэ."
        else:
            j=', '.join(f"{l} ({p})" for p,l in zip(parts,lbl))
            card['story']=f"{j} хослон «{meaning}» гэсэн утга үүсгэнэ."
        card['mnemonic']={'parts':parts,'result':ch,'meaning':meaning}
        comp+=1
    else:
        card['structure']={'parts':[],'result':{'char':ch,'label':meaning}}
        card['story']=f"«{meaning}» гэсэн утгатай үндсэн дүрс ханз ({py})."
        simp+=1
    cards.append(card); by[ch]=card; added+=1

DRAFTS.write_text(json.dumps(cards,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f"HSK2 CH: {len(CH)} | шинээр нэмсэн: {added} | drafts-д аль хэдийн байсан: {existing}")
print(f"compound: {comp} | simple: {simp} | 多音字 override: {pyov} | нийт drafts: {len(cards)}")
print("жишээ-пиньин олдоогүй:", exfb if exfb else "байхгүй ✓")
